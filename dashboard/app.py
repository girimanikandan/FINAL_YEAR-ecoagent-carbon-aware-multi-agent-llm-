"""EcoAgent-CG dashboard - home. Run with:  streamlit run dashboard/app.py"""
import streamlit as st
from common import CFG, PROC, RAW, C, list_runs, page, read_csv

page("EcoAgent-CG v1 — Overview")
st.caption("Carbon-aware multi-agent code generation · Rajalakshmi Institute of Technology, Chennai · every number below is read from results/ (generated by the analysis scripts)")

runs = list_runs()
c1, c2, c3, c4 = st.columns(4)
c1.metric("Runs on disk", len(runs))
c2.metric("Tasks completed", int(runs.tasks_done.sum()) if len(runs) else 0)
cal = (PROC / "htde_calibration.json").exists()
c3.metric("HTDE calibrated", "yes" if cal else "no — run the pilot")
c4.metric("Analysis files", len(list(PROC.glob("*.csv"))))

st.subheader("Main comparison")
main = read_csv("main_results.csv")
if main is None:
    st.info("No analysed results yet. Go to **Run Control**: run the pilot → run the main experiment → run analysis.")
else:
    cols = ["system", "task_success", "final_test_pass_rate", "quality_retention_pct", "emissions_per_task_gco2eq",
            "carbon_quality_efficiency", "agent_calls", "agent_graph_depth", "retry_count", "latency_seconds", "n_tasks", "n_runs"]
    st.dataframe(main[[c for c in cols if c in main.columns]].round(4), hide_index=True)
    fig = C.path(CFG, "figures") / "fig_pareto.png"
    if fig.exists():
        st.image(str(fig), caption="Quality vs emissions", width=520)

st.subheader("Setup status")
from src.carbon.intensity import CarbonContext
rows = []
for p in ("low", "medium", "high"):
    try:
        ctx = CarbonContext(CFG, p)
        rows.append({"profile": p, "source": ctx.trace.source, "real data": ctx.trace.is_real, "mean gCO2/kWh": round(float(ctx.trace.values.mean()), 1),
                     "low/high tercile": f"{ctx.thresholds[0]:.1f} / {ctx.thresholds[1]:.1f}"})
    except FileNotFoundError:
        rows.append({"profile": p, "source": "MISSING", "real data": False})
import pandas as pd
st.dataframe(pd.DataFrame(rows), hide_index=True)
st.caption("Use the sidebar pages: Run Control · Live Monitor · Results · Task Drilldown · Carbon · Config · Playground")
